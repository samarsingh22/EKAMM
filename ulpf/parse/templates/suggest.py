"""``suggest_source_definition`` — auto-draft a source YAML from mined samples.

THE KEY DIFFERENTIATING FEATURE. Every other module in this package answers
"what shape is this line?" (:mod:`~ulpf.parse.templates.miner`), "have we seen
it before?" (:mod:`~ulpf.parse.templates.store`), and "what does each variable
position probably mean?" (:mod:`~ulpf.parse.templates.inference`). This module
is where those three answers become the thing an operator actually needs:
**requirement (i) — reduced parser development effort** — a complete,
schema-valid ``configs/sources/*.yaml`` draft, generated without anyone
hand-writing a grok pattern or guessing at OCSF field paths.

STRATEGY
--------
1. Sniff the samples' format (:func:`~ulpf.detect.sniffer.sniff_layered`,
   majority vote across the sample set).
2. **Structured** (``json``/``kv``/``cef``/``leef``) — run the real parse
   engine over every sample, take the union of observed keys, and map
   straight from key name -> value column. High confidence: the parser
   already told us the field boundaries: no guessing about where one value
   ends and the next begins.
3. **Delimited** (``csv``/``tsv``) — split every sample on the delimiter and
   treat each column position like an unstructured wildcard (below);
   generates a ``csv`` engine definition with inferred column names.
4. **Unstructured** — mine the dominant template
   (:class:`~ulpf.parse.templates.miner`, using the same masking config as
   the live pipeline) and run every sample's parameter list through
   :func:`~ulpf.parse.templates.inference.infer_field_types`. Builds a
   **dissect** pattern (``%{field}`` placeholders, the literal template text
   supplies the delimiters) when every gap between placeholders is
   non-empty; falls back to **grok** only when it is not (dissect cannot
   place an unambiguous boundary between two back-to-back placeholders).
5. **Detect rule**: the longest, most distinctive literal substrings common
   to every sample (for delimited formats, a ``field_count`` fallback).
6. **Semantic -> OCSF**: a fixed table (``source_ip`` -> ``src_endpoint.ip``,
   ``port`` -> ``src_endpoint.port``/``dst_endpoint.port`` by proximity to the
   nearest IP, ``action`` -> ``action_id``/``action``/``disposition`` via a
   value map, ...). Anything left over (``unknown``, a third+ IP, an
   unresolved port/byte slot) is never dropped — it still reaches
   ``unmapped: keep_all``.
7. The returned YAML carries a header comment naming the template/source it
   came from, how many samples, and each field's confidence, plus an inline
   ``# REVIEW REQUIRED`` comment on every mapping whose confidence is below
   :data:`REVIEW_THRESHOLD`. It is **always** re-parsed and validated against
   :class:`~ulpf.parse.dsl.schema.SourceDefinition` before being returned —
   an internal bug here must raise :class:`SuggestError`, never hand back
   YAML that would fail to load.

This is a draft, not an oracle: it is meant to turn a blank page into a
95%-there starting point an operator reviews and commits — not to bypass
human review of what an autogenerated parser does with real evidence.
"""

