def resolve_sample_lines(
    source_id: str,
    *,
    template_id: str | int | None = None,
    sample_lines: list[str] | None = None,
    settings: Settings | None = None,
    template_store: TemplateStore | None = None,
) -> list[str]:
    """Resolve the raw lines a caller wants — either given directly, or looked
    up from ``template_store`` by ``template_id``.

    Used by :func:`suggest_source_definition` itself, and by
    ``ulpf suggest-parser``/the API to get the *same* lines back for
    :func:`~ulpf.parse.templates.score.score_suggestion` without generating
    twice or duplicating the lookup.

    Raises:
        ValueError: Neither or both of ``template_id``/``sample_lines`` given.
        SuggestError: ``template_id`` given but not found for ``source_id``.
    """
    if (template_id is None) == (sample_lines is None):
        raise ValueError("pass exactly one of template_id or sample_lines")
    if template_id is not None:
        store = template_store or TemplateStore(settings or get_settings())
        return _lookup_sample_lines(store, source_id, template_id)
    return [line for line in (sample_lines or []) if line and line.strip()]


def suggest_source_definition(
    source_id: str,
    *,
    template_id: str | int | None = None,
    sample_lines: list[str] | None = None,
    settings: Settings | None = None,
    template_store: TemplateStore | None = None,
    name: str | None = None,
    vendor: str | None = None,
    product: str | None = None,
    min_samples: int = _MIN_SAMPLES,
) -> str:
    """Draft a complete source-definition YAML from sample raw lines.

    Args:
        source_id: The device/listener the samples came from (used for the
            template lookup and as a default vendor/product/name hint).
        template_id: Look up this template's stored samples via ``template_store``.
            Exactly one of ``template_id`` / ``sample_lines`` must be given.
        sample_lines: Raw lines to analyze directly (bypasses the store's
            5-sample cap — this is what ``ulpf suggest-parser --file`` uses).
        settings: Only consulted when ``template_id`` is given (to build the
            default ``template_store``).
        template_store: Override for tests.
        name/vendor/product: Override the derived source name / metadata.
        min_samples: Refuse to guess from fewer than this many usable lines.

    Returns:
        A complete YAML document, already validated against
        :class:`~ulpf.parse.dsl.schema.SourceDefinition`.

    Raises:
        ValueError: Neither or both of ``template_id``/``sample_lines`` given.
        SuggestError: Too few usable samples, or (should never happen) the
            generated document failed schema validation.
    """
    lines = resolve_sample_lines(
        source_id,
        template_id=template_id,
        sample_lines=sample_lines,
        settings=settings,
        template_store=template_store,
    )

    if len(lines) < min_samples:
        raise SuggestError(f"need at least {min_samples} sample lines, got {len(lines)}")

    outer, inner = _majority_format(lines)
    if inner in _KEYED_ENGINES:
        spec = _keyed_definition(inner, lines, outer)
    elif inner in _DELIMITED_FORMATS:
        spec = _delimited_definition(inner, lines, outer, _DELIMITED_FORMATS[inner])
    else:
        spec = _unstructured_definition(lines, outer)

    slug = _slugify(name or source_id)
    doc, review = _build_doc(slug, vendor, product, spec)
    header = _header_comment(source_id, template_id, len(lines), spec)

    body = yaml.safe_dump(doc, sort_keys=False, default_flow_style=False, allow_unicode=True)
    body = _annotate_review_lines(body, review)
    final_text = header + body

    _validate_or_raise(final_text)
    return final_text


