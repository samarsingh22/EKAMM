def _slugify(text: str) -> str:
    slug = re.sub(r"[^a-z0-9_-]+", "_", text.lower()).strip("_-")
    return slug if slug and slug[0].isalnum() else f"src_{slug}" if slug else "suggested_source"


def _build_doc(
    slug: str, vendor: str | None, product: str | None, spec: _BuiltSpec
) -> tuple[dict[str, Any], dict[str, float]]:
    fields, review = _assign_ocsf(spec.pfields)
    if "time" not in fields and spec.parse.get("envelope") == "syslog":
        # no field in the body itself looked like a timestamp, but the syslog
        # envelope always carries one - fall back to it (see iptables.yaml)
        fields["time"] = {"from": "envelope.timestamp", "type": "timestamp", "required": True}
    required = ["class_uid", "category_uid"]
    required.extend(
        path for path in ("src_endpoint.ip", "dst_endpoint.ip", "time") if path in fields
    )

    doc = {
        "name": slug,
        "version": "0.1.0-suggested",
        "vendor": vendor or "Unknown",
        "product": product or slug,
        "product_version": "unknown",
        "detect": spec.detect,
        "parse": spec.parse,
        "normalize": {
            "class_uid": 4001,
            "category_uid": 4,
            "activity_id": 6,
            "constants": {
                "metadata.product.vendor_name": vendor or "Unknown",
                "metadata.product.name": product or slug,
                "severity_id": 1,
            },
            "fields": fields,
            "unmapped": "keep_all",
        },
        "validate": {"required": required, "on_failure": "dead_letter"},
    }
    return doc, review


def _header_comment(
    source_id: str, template_id: str | int | None, n_samples: int, spec: _BuiltSpec
) -> str:
    template_note = template_id if template_id is not None else "n/a (built from raw sample lines)"
    lines = [
        "# Auto-generated by `ulpf suggest-parser` — REVIEW BEFORE DEPLOYING.",
        f"# source_id: {source_id}",
        f"# template_id: {template_note}",
        f"# generated from: {n_samples} sample line(s) ({spec.samples_used} used after sniffing)",
        f"# detection strategy: {spec.kind}",
        "#",
        "# per-field confidence:",
    ]
    for pf in spec.pfields:
        guess = pf.guess
        flag = "  <- REVIEW" if guess["confidence"] < REVIEW_THRESHOLD else ""
        lines.append(
            f"#   {pf.name}: {guess['inferred_semantic']} "
            f"(confidence {guess['confidence']:.2f}, mask={guess['mask_type']}){flag}"
        )
    lines.append("")
    return "\n".join(lines) + "\n"


def _annotate_review_lines(body: str, review: dict[str, float]) -> str:
    lines_out = body.splitlines()
    for path, confidence in review.items():
        pattern = re.compile(r"^(\s*)" + re.escape(path) + r":\s*$")
        for i, line in enumerate(lines_out):
            if pattern.match(line):
                lines_out[i] = f"{line}  # REVIEW REQUIRED (confidence {confidence:.2f})"
                break
    return "\n".join(lines_out) + "\n"


def _lookup_sample_lines(store: TemplateStore, source_id: str, template_id: str | int) -> list[str]:
    target = str(template_id)
    for row in store.list_templates(source_id=source_id):
        if row["template_id"] == target:
            return list(row["sample_lines"])
    raise SuggestError(f"no template {template_id!r} recorded for source_id {source_id!r}")


def _validate_or_raise(yaml_text: str) -> None:
    """Never return YAML that would fail to load — validate before handing it back."""
    try:
        parsed = yaml.safe_load(yaml_text)
        load_source_definition(parsed)
    except (_PydanticValidationError, yaml.YAMLError) as exc:
        raise SuggestError(f"generated definition failed validation: {exc}") from exc
